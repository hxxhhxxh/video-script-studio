def script_prompt(beats_json: str, target_seconds: int, style_hint: str,
                  aspect: str, extra_notes: str) -> str:
    style_line = f"整体风格参考：{style_hint}" if style_hint.strip() else "整体风格请你根据内容自行判断并写清楚"
    notes_line = f"额外要求：{extra_notes.strip()}" if extra_notes.strip() else "无额外要求"
    return f"""你是资深短视频导演。下面是从原视频提炼出的叙事节拍（JSON）。

【总时长目标】成片约 {target_seconds} 秒　【画面比例】{aspect}
【{style_line}】
【{notes_line}】

【任务】只写剧本，不要写人物档案、不要写分镜。
1. 保留原片核心事实与事件顺序，重新组织结构、重写表达，适合竖屏短视频。
2. 第一场必须有钩子（前 3 秒抓人），不要从背景铺垫开始。
3. 禁止凭空添加原文没有的年代、人名、数据、地名。
4. scenes 分 4–8 场，每场 voiceover 60–150 字，duration 为该场秒数，合计贴近 {target_seconds} 秒。
5. summary 不超过 40 字。

【叙事节拍 JSON】
{beats_json}

【输出要求】只输出 JSON，不要解释、不要 Markdown 代码块。结构：
{SCRIPT_SCHEMA}"""


def characters_prompt(beats_json: str, style_hint: str) -> str:
    style_line = f"【整体风格】{style_hint}" if style_hint.strip() else ""
    return f"""你是影视造型指导。下面是从原视频提炼出的叙事节拍（JSON），里面散落着人物线索。

【任务】整理出完整角色档案，每个出场人物一份。
1. 年龄、性别、穿戴（上衣/下装/鞋/材质/颜色）、配饰与随身道具必须写具体；
   原文没写就按年代与身份合理设定，但必须与叙事一致。
2. anchor_cn / anchor_en 是给生图或生视频工具用的锚定提示词：把五官、发型、服装材质颜色、
   配饰、气质压成一段话（中文 80 字以内，英文 60 词以内），多镜头复用时不能跑脸。
3. 角色数量 1–4 个，群像合并成一个。
{style_line}

【叙事节拍 JSON】
{beats_json}

【输出要求】只输出 JSON，不要解释、不要 Markdown 代码块。结构：
{CHARS_SCHEMA}"""


def shots_prompt(beats_json: str, scenes_json: str, chars_json: str,
                 target_seconds: int, aspect: str) -> str:
    return f"""你是分镜师 + AI 视频提示词工程师。下面是角色档案、剧本场景与叙事节拍。

【任务】把剧本拆成连续分镜，逐镜头给时长与生成提示词。
1. 每镜头时长只能是 5 秒或 10 秒；镜头总数 8–14 个；所有镜头秒数合计贴近 {target_seconds} 秒。
2. 画面比例 {aspect}；叙事镜头与特写镜头比例约 6:4。
3. prompt_cn 必须包含：主体与动作、环境与时代感、光线氛围、镜头语言（景别+角度+运镜）、质感关键词；
   一段话写完整，不超过 120 字，且要与角色档案的外观一致（写明“与角色锚定一致”）。
4. prompt_en 为对应英文，60 词以内；negative 写要避免的东西（多指、脸部变形、文字水印、现代物件），20 字以内。
5. 第一个镜头必须是抓人的画面（特写或强冲突）。
6. 只写分镜，不要重复输出剧本或人物档案。

【角色档案】
{chars_json}

【剧本场景】
{scenes_json}

【叙事节拍】
{beats_json}

【输出要求】只输出 JSON，不要解释、不要 Markdown 代码块。结构：
{SHOTS_SCHEMA}"""


REPAIR_PROMPT = """你上一次的输出不是合法 JSON，无法被程序解析。

解析器报错：{error}

请重新输出。要求：
1. 只输出 JSON 本体，不要任何前言、后记、解释或 Markdown 代码块标记。
2. 所有字符串用双引号，不要有尾随逗号，不要有注释。
3. 必须完整包含之前要求的所有字段，缺字段视为失败。
4. 如果某个字段确实没有内容，用空字符串或空数组，不要省略字段名。

原任务要求回顾：
{schema_hint}"""


