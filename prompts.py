# ─────────────────────────────────────────────────────────────
# 1. 逐段提炼
# ─────────────────────────────────────────────────────────────

def beats_prompt(chunk_text: str, index: int, total: int) -> str:
    return f"""你是短视频编剧的分析助手。下面是一段视频转录文字的第 {index}/{total} 块。

【任务】只做提炼，不要改写、不要创作、不要补充原文没有的信息。
1. 把这一块拆成若干个"叙事节拍"（一个节拍 = 一个可以独立成镜头的动作或信息点）。
2. 找出这一块里出现的所有人物，提取他们的年龄、性别、穿戴、配饰、气质。
   · 原文写了就照抄关键词；没写就写"未提及"，绝对不要编造。
3. 标出最值得保留的原话。

【转录原文】
{chunk_text}

【输出要求】
只输出 JSON，不要任何解释文字、不要 Markdown 代码块。
结构严格如下：
{BEATS_SCHEMA}"""


# ─────────────────────────────────────────────────────────────
# 2. 总装：剧本 + 人物 + 分镜
# ─────────────────────────────────────────────────────────────

def assemble_prompt(beats_json: str, target_seconds: int, style_hint: str,
                    aspect: str, extra_notes: str) -> str:
    style_line = f"整体风格参考：{style_hint}" if style_hint.strip() else "整体风格请你根据内容自行判断并写清楚"
    notes_line = f"额外要求：{extra_notes.strip()}" if extra_notes.strip() else "无额外要求"
    return f"""你是资深短视频导演 + 分镜师 + AI 视频提示词工程师。下面是从原视频提炼出的叙事节拍（JSON）。

【总时长目标】成片约 {target_seconds} 秒
【画面比例】{aspect}
【{style_line}】
【{notes_line}】

【工作步骤】
第一步：写一个改写版剧本。保留原片的核心事实与事件顺序，但重新组织结构、重写表达，
让叙事更适合竖屏短视频（前 3 秒必须有钩子）。可以调整节奏和视角，禁止凭空添加原文没有的
年代、人名、数据、地名。

第二步：给每个出场人物做一份"可复用外观档案"，必须明确写出年龄、性别、穿戴、配饰。
anchor_cn / anchor_en 要是完整的、能直接粘贴进生图或生视频工具的一段话，
写清五官、发型、服装材质与颜色、配饰、气质，多次出现要保持一致（多镜头不能变脸）。

第三步：把剧本拆成连续分镜，逐镜头给时长与生成提示词。
· 每个镜头时长只能是 5 秒或 10 秒（对齐主流 AI 视频模型），所有镜头加起来贴近 {target_seconds} 秒。
· 镜头数量控制在 8–14 个之间，叙事镜头与特写镜头比例约 6:4。
· 每个镜头的 prompt_cn 必须包含：主体与动作、环境与时代感、光线氛围、镜头语言（景别+角度+运镜）、
  质感关键词。一段话写完整，不要分点罗列，**每条不超过 120 字**（写长了会被截断）。
· 整体风格只在 style 字段写一次，单镜头提示词里不要重复堆砌风格词。
· 第一个镜头必须是能抓住人的画面（特写或强冲突），不要从背景介绍开始。
· negative 写清要避免的东西（例如：多指、脸部变形、文字水印、现代物件），不超过 20 字。

【叙事节拍 JSON】
{beats_json}

【输出要求】
只输出 JSON，不要任何解释文字、不要 Markdown 代码块。结构严格如下：
{FINAL_SCHEMA}"""


