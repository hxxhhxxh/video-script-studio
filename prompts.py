"""提示词配方（Prompt Recipes）

这个文件是整个系统的"大脑说明书"：所有交给大模型的指令都在这里，
你可以直接改中文描述来调整产出风格，不用动其他代码。

三组配方：
  1. BEATS_*     逐段提炼：把长转录切成块，每块抽"叙事节拍 + 人物线索"
  2. ASSEMBLE_*  总装：把节拍汇总成「改写剧本 + 人物画像 + 分镜表」
  3. REPAIR_*    JSON 解析失败时的修复追问

设计原则（来自美食/故事号 SOP 的踩坑经验）：
  · 分镜时长只允许 5 秒或 10 秒，与主流 AI 视频模型对齐
  · 人物外观必须给"可复用的锚定描述"，否则多镜头之间角色会变脸
  · 每个镜头提示词必须自带：主体 / 动作 / 环境 / 光线 / 镜头 / 质感 / 风格锚
  · 不允许模型自行补充原文没有的年代、人名、数据
"""

